// Layer 2 of the catalog audit: `npm run gym:audit:semantic`. GYM_PROGRAM.md §12a.
//
// Layer 1 (scripts/gym-audit.mjs) answers everything with a right answer. This
// one answers the question that needs judgement:
//
//     Does this exercise actually mean what its name says, given the equipment
//     it lists — and does its metadata match the exercise?
//
// SIX relationships, not two. The first two catch a Pallof press that has no
// lateral resistance to press against. The other four catch the rows that PASS
// those and are still poison: `Side-Lying Dumbbell External Rotation` is a real
// exercise, correctly named, doable with a dumbbell — and tagged
// `progressionMode: load` it makes the app spend months telling you to chase a
// heavier cuff weight. Nothing about that row looks wrong.
//
// The rule this file exists to respect: THIS IS CLAUDE POLICING CLAUDE-GENERATED
// DATA. So nothing it says is taken on trust —
//
//   * it never sees a row that failed layer 1;
//   * every value it returns is re-validated against layer 1's own enums, and
//     an illegal one forces the row to `review` rather than being written;
//   * it is told that `review` is a perfectly good answer;
//   * `timeEstimate` is NOT asked for — code owns every number that affects
//     execution (§12a), and exerciseSeconds() already derives it;
//   * anything `review`, or `approved` at low confidence, lands in a queue for
//     a human. Nothing becomes production because a model said so.
//
// Flags:
//   --dry-run     print the verdicts, write nothing   (start here)
//   --refresh     re-audit rows that already have a catalogStatus
//   --only-review re-audit only the rows currently sitting in `review`
//   --limit=N     only the first N rows — for checking the prompt cheaply
//   --batch=N     rows per model call (default 20)
//   --model=NAME / --effort=LEVEL   (default: opus / medium)
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { getDoc, setDoc } from 'firebase/firestore'
import {
  auditLayer1,
  catalogRef,
  MOVEMENT_PATTERNS,
  PRIMARY_ROLES,
  LATERALITY,
  PROGRESSION_MODES,
  RISK_LEVELS,
  RISK_JOINTS,
  CATALOG_STATUS,
  AUDIT_CONFIDENCE,
  REVIEW_FLAGS,
  BLOCKING_FLAGS,
} from './gym-audit.mjs'

const args = process.argv.slice(2)
const flag = (n, d) => {
  const hit = args.find((a) => a.startsWith(`--${n}=`))
  return hit ? hit.slice(n.length + 3) : d
}
const DRY = args.includes('--dry-run')
const REFRESH = args.includes('--refresh')
const ONLY_REVIEW = args.includes('--only-review')
const LIMIT = Number(flag('limit', 0)) || 0
const BATCH = Number(flag('batch', 20)) || 20
const MODEL = flag('model', 'opus')
const EFFORT = flag('effort', 'medium')

const list = (a) => a.join(' · ')

function prompt(rows, equipment) {
  const gear = equipment
    .filter((e) => !e.retired)
    // NOT truncated. The notes are the only description of the gear the model
    // ever gets, and a 220-char cut once hid an owner-confirmed correction that
    // had been appended to the end of a long note — the model went on answering
    // from the stale first sentence for a whole round.
    .map((e) => `  ${e.id} — ${e.name}${e.notes ? `: ${e.notes}` : ''}`)
    .join('\n')

  return `You are auditing a home-gym exercise catalog. Earlier rows were generated by an AI
from photographs and were never checked, so some of them are wrong. Your job is to catch that.

THE EQUIPMENT THAT EXISTS. Nothing else is available — no cable machine, no barbell, no
resistance bands (they are on order but NOT yet here), no plyo box, no landmine:
${gear}

For EACH exercise below, check SIX relationships and then tag it.

  1. NAME vs MOVEMENT — does the name describe what the body actually does?
  2. EQUIPMENT vs MOVEMENT — can the listed equipment physically produce this movement?
     The known failure: a "Pallof press" needs resistance anchored to the SIDE of the body.
     A dumbbell held at the chest produces no lateral force, so a dumbbell Pallof press is
     not a Pallof press. Look for the same shape of error elsewhere — exercises whose
     defining feature is the DIRECTION or SOURCE of resistance rather than a body position.
  3. movementPattern vs MOVEMENT — this also drives recovery tracking, so a carry tagged
     as a pull corrupts more than the slot it fills. Use "isolation" for single-joint
     accessory work that fits none of the compound patterns (leg extension, leg curl,
     wrist curl, biceps curl, calf raise) — the muscle is recorded separately, so
     "isolation" is a correct and complete answer, not a fallback.
  4. primaryRole vs EXERCISE — rotator-cuff work tagged "strength" gets loaded and
     progressed like a bench press.
  5. progressionMode vs EXERCISE — HOW does this exercise get harder over time?
     load       add weight (dumbbell press, goblet squat)
     reps       add reps at bodyweight (push-up, chin-up)
     duration   hold longer (plank, dead hang) — timed exercises only
     difficulty harder variation (dead bug → hollow hold; bent-knee → straight-leg Copenhagen)
     quality    jumps and throws — these are NEVER progressed by reps or load, they are
                terminated when speed or height drops
     none       mobility and warm-up movements
  6. riskProfiles vs EXERCISE — back / shoulder / knee, each low|moderate|high.
     "high" means this exercise meaningfully loads that joint in a vulnerable position:
     loaded spinal flexion or rotation → back:high; heavy overhead or end-range external
     rotation → shoulder:high; deep loaded knee flexion or hard landings → knee:high.
     This flag GATES what the athlete is asked to do, so it is the most expensive to get wrong.

THE ATHLETE, so you can judge risk — there is exactly ONE, judge against nobody else:
43 years old, plays a lot of pickleball, priorities are lower-back resilience,
trunk/anti-rotation strength, chest and abs.

TAG each exercise:
  reviewFlags:     which KIND of problem, so a human knows what they are being asked to judge.
                   All five are booleans; set only the ones that apply.
     physicalSetup      the gear may not physically allow this setup (does the bench decline?)
     movementDefinition the name does not describe the movement (the Pallof failure)
     metadata           a tag is wrong (pattern, role, laterality, progressionMode, risk)
     loadSuitability    the lightest available load is wrong for the movement's purpose
     programFit         real and correctly described, but a poor fit for THIS athlete's goals

  catalogStatus:   approved  — usable as data. Set this whenever the ONLY flag is programFit:
                               the catalog records what is POSSIBLE, and choosing what is worth
                               doing is the program's job, not the catalog's.
                   review    — any of the other four flags is set, or you are unsure. THIS IS A
                               GOOD ANSWER. A human reads every one. Guessing "approved" to seem
                               decisive is the only actually harmful answer here.
                   retired   — the exercise is impossible or meaningless with this equipment
  auditConfidence: high | medium | low
  auditReason:     REQUIRED unless catalogStatus is "approved" AND auditConfidence is "high".
                   One sentence, concrete: name the relationship that fails and why.

Legal values, use these EXACT strings:
  movementPattern: ${list(MOVEMENT_PATTERNS)}
  primaryRole:     ${list(PRIMARY_ROLES)}
  laterality:      ${list(LATERALITY)}  (perSide = the prescribed reps are done left, then right)
  progressionMode: ${list(PROGRESSION_MODES)}
  risk levels:     ${list(RISK_LEVELS)}

THE EXERCISES:
${rows
  .map(
    (e, i) =>
      `${i + 1}. ${e.name} [${e.kind}, intensity ${e.intensity}, ${e.defaultSets}×${e.defaultReps}${e.perSide ? ', flagged perSide' : ''}]
   equipment: ${(e.equipmentIds ?? []).length ? e.equipmentIds.join(', ') : '(none — bodyweight)'}
   how: ${e.how ?? '(no instructions)'}`,
  )
  .join('\n')}

Answer with ONLY a JSON array, one object per exercise, same order, no prose, no markdown fence:
[{"n":1,"name":"echo the name back exactly","movementPattern":"...","primaryRole":"...","laterality":"...","progressionMode":"...","riskProfiles":{"back":"low","shoulder":"low","knee":"low"},"reviewFlags":{"physicalSetup":false,"movementDefinition":false,"metadata":false,"loadSuitability":false,"programFit":false},"catalogStatus":"approved","auditConfidence":"high","auditReason":""}]`
}

function ask(text) {
  const out = execFileSync('claude', ['--model', MODEL, '--effort', EFFORT, '-p', text], {
    encoding: 'utf8',
    maxBuffer: 32 * 1024 * 1024,
  })
  const start = out.indexOf('[')
  const end = out.lastIndexOf(']')
  if (start === -1 || end === -1) throw new Error(`No JSON array in claude's reply:\n${out.slice(0, 800)}`)
  return JSON.parse(out.slice(start, end + 1))
}

/**
 * Re-validate everything the model said. An illegal value does not throw and
 * does not get written — it forces the row to `review` with a reason saying so,
 * which is the honest outcome: we learned nothing about that row.
 */
function sanitise(v, e) {
  const bad = []
  const pick = (field, legal) => {
    if (legal.includes(v?.[field])) return v[field]
    bad.push(`${field}="${v?.[field]}"`)
    return undefined
  }

  const out = {
    movementPattern: pick('movementPattern', MOVEMENT_PATTERNS),
    primaryRole: pick('primaryRole', PRIMARY_ROLES),
    laterality: pick('laterality', LATERALITY),
    progressionMode: pick('progressionMode', PROGRESSION_MODES),
    auditConfidence: AUDIT_CONFIDENCE.includes(v?.auditConfidence) ? v.auditConfidence : 'low',
  }

  const risk = {}
  for (const joint of RISK_JOINTS) {
    const level = v?.riskProfiles?.[joint]
    if (RISK_LEVELS.includes(level)) risk[joint] = level
    else bad.push(`riskProfiles.${joint}="${level}"`)
  }
  out.riskProfiles = risk

  // the flags are the evidence; the status is derived from them rather than
  // taken on the model's word, so "approved" with a blocking flag set cannot happen
  const flags = {}
  for (const f of REVIEW_FLAGS) flags[f] = v?.reviewFlags?.[f] === true
  out.reviewFlags = flags

  let status = CATALOG_STATUS.includes(v?.catalogStatus) ? v.catalogStatus : 'review'
  if (!CATALOG_STATUS.includes(v?.catalogStatus)) bad.push(`catalogStatus="${v?.catalogStatus}"`)
  if (status === 'approved' && BLOCKING_FLAGS.some((f) => flags[f])) status = 'review'

  let reason = String(v?.auditReason ?? '').trim()
  if (bad.length) {
    status = 'review'
    out.auditConfidence = 'low'
    reason = `Model returned illegal values (${bad.join(', ')}). ${reason}`.trim()
  }
  // an approved row with no reason is fine; anything else has to justify itself
  if (status !== 'approved' && !reason) reason = 'Model gave no reason — treat as unreviewed.'

  // a contradiction between the model and the flag the app already uses is
  // exactly the kind of thing a human should look at, not something to smooth over
  if (out.laterality === 'perSide' && e.perSide !== true) {
    status = status === 'approved' ? 'review' : status
    reason = `${reason} Model says perSide but the catalog flag is not set.`.trim()
  }

  out.catalogStatus = status
  out.auditReason = reason
  return out
}

async function main() {
  const ref = await catalogRef()
  const snap = await getDoc(ref)
  if (!snap.exists()) throw new Error('app/gymCatalog does not exist')
  const data = snap.data()

  // the gate: layer 1 first, and only its clean rows go any further
  const { findings, equipment, exercises, clean } = auditLayer1(data)
  const errors = findings.filter((f) => f.level === 'error')
  if (errors.length) {
    console.error(`\n❌ Layer 1 has ${errors.length} error(s). Fix those first — run \`npm run gym:audit\`.\n`)
    process.exit(1)
  }

  let todo = clean.filter((e) => (ONLY_REVIEW ? e.catalogStatus === 'review' : REFRESH || !e.catalogStatus))
  if (LIMIT) todo = todo.slice(0, LIMIT)

  console.log(`\n🧠 Layer 2 — semantic audit`)
  console.log(`   ${clean.length} live rows passed layer 1 · ${todo.length} to audit · ${MODEL}/${EFFORT}\n`)
  if (todo.length === 0) {
    console.log('Nothing to do. Use --refresh to re-audit rows that already have a status.\n')
    process.exit(0)
  }

  const verdicts = new Map()
  const norm = (s) => String(s ?? '').toLowerCase().replace(/[^a-z0-9]+/g, '')

  for (let i = 0; i < todo.length; i += BATCH) {
    const batch = todo.slice(i, i + BATCH)
    process.stdout.write(`   batch ${Math.floor(i / BATCH) + 1}/${Math.ceil(todo.length / BATCH)} (${batch.length} rows)… `)
    const answers = ask(prompt(batch, equipment))
    // match on the echoed name, never on position — one dropped row would
    // otherwise shift every verdict after it onto the wrong exercise
    const byName = new Map(answers.map((a) => [norm(a.name), a]))
    let hit = 0
    for (const e of batch) {
      const a = byName.get(norm(e.name))
      if (!a) continue
      verdicts.set(e.id, sanitise(a, e))
      hit++
    }
    console.log(`${hit}/${batch.length}`)
  }

  const missing = todo.filter((e) => !verdicts.has(e.id))
  const got = [...verdicts.entries()]
  const flagged = got.filter(([, v]) => v.catalogStatus !== 'approved' || v.auditConfidence === 'low')

  console.log(`\n📋 ${got.length} audited`)
  const counts = {}
  for (const [, v] of got) counts[v.catalogStatus] = (counts[v.catalogStatus] ?? 0) + 1
  for (const [k, n] of Object.entries(counts)) console.log(`   ${k}: ${n}`)

  if (flagged.length) {
    const byId = new Map(exercises.map((e) => [e.id, e]))
    console.log(`\n🚩 ${flagged.length} need a human — nothing here is written as approved:`)
    for (const [id, v] of flagged) {
      console.log(`\n   ${byId.get(id)?.name}  [${v.catalogStatus} · ${v.auditConfidence}]`)
      console.log(`      ${v.auditReason}`)
    }
  }
  if (missing.length) console.log(`\n⚠️  No verdict for ${missing.length}, left untouched: ${missing.map((e) => e.name).join(', ')}`)

  if (DRY) {
    console.log('\n🧪 --dry-run: nothing written.\n')
    process.exit(0)
  }

  const stamp = new Date().toISOString().replace(/[:.]/g, '-')
  const backup = `.gym-catalog-backup-${stamp}.json`
  writeFileSync(backup, JSON.stringify(data, null, 2))

  const next = exercises.map((e) => (verdicts.has(e.id) ? { ...e, ...verdicts.get(e.id) } : e))
  await setDoc(ref, { ...data, exercises: next, updatedAt: new Date().toISOString() })
  console.log(`\n💾 Backed up to ${backup}`)
  console.log('✅ Saved. Run `npm run gym:audit` to see the coverage bars.\n')
  process.exit(0)
}

main().catch((e) => {
  console.error('❌', e.message ?? e)
  process.exit(1)
})
