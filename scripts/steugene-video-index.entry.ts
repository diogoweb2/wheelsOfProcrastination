// 🏫 St. Eugene 7 (§24z) — write `src/steugene/videoIndex.ts` from the packs.
//
// The shelf at `/steugene7/videos` lists every video in the year, grouped by
// chapter and page. It cannot do that by reading the packs: 105 packs is ~4 MB
// of lesson content split into one lazy chunk each (§24k), and a page that
// pulls all of them to print 108 titles costs him the whole download to look
// at a list.
//
// So the titles are lifted out into one small index — a few kB, bundled with
// the app, no fetch at all. The packs stay the only place a video is authored;
// this file just copies the labels off them. `npm run se:audit` fails when the
// copy has drifted, which is what stops the shelf quietly going stale.
import { writeFileSync } from 'node:fs'
import { seAllSubtopics } from '../src/logic/steugene'
import { ensurePack, writtenSubtopics } from '../src/steugene/packs'
import type { SeVideoRef } from '../src/steugene/types'

/** Every video in every pack, in curriculum order. The index IS this list. */
export async function collectVideos(): Promise<SeVideoRef[]> {
  const written = writtenSubtopics()
  const out: SeVideoRef[] = []
  for (const { subtopic } of seAllSubtopics()) {
    if (!written.has(subtopic.id)) continue
    const pack = await ensurePack(subtopic.id)
    if (!pack) continue
    for (const [blocks, bench] of [
      [pack.core, false],
      [pack.extra, true],
    ] as const) {
      for (const b of blocks) {
        if (b.kind !== 'video') continue
        out.push({
          id: b.id,
          subtopicId: subtopic.id,
          youtube: b.youtube,
          title: b.title,
          ...(b.by ? { by: b.by } : {}),
          seconds: b.seconds,
          ...(b.start ? { start: b.start } : {}),
          ...(b.end ? { end: b.end } : {}),
          ...(b.watchFor ? { watchFor: b.watchFor } : {}),
          checks: b.checks.length,
          ...(bench ? { bench: true as const } : {}),
        })
      }
    }
  }
  return out
}

const HEAD = `// 🏫 St. Eugene 7 (§24z) — every video in the year, as a list of labels.
//
// GENERATED by \`npm run se:video-index\`. Do not edit by hand: a video is
// authored in its pack (\`src/steugene/packs/\`) and only copied here, and
// \`npm run se:audit\` fails when this file and the packs disagree.
//
// It exists so the 🎬 shelf can be a list rather than a download. The packs
// are one lazy chunk each (§24k) and there are 105 of them; printing 100-odd
// titles is not worth 4 MB, and the only thing the shelf needs from a pack is
// the YouTube id and the title. Playing a video needs nothing else either —
// the questions that follow it in a lesson stay in the pack, where they are
// the lesson's business and not the shelf's (§24g).
import type { SeVideoRef } from './types'
`

const line = (v: SeVideoRef) => {
  const bits = [`id: ${JSON.stringify(v.id)}`, `subtopicId: ${JSON.stringify(v.subtopicId)}`, `youtube: ${JSON.stringify(v.youtube)}`, `title: ${JSON.stringify(v.title)}`]
  if (v.by) bits.push(`by: ${JSON.stringify(v.by)}`)
  bits.push(`seconds: ${v.seconds}`)
  if (v.start) bits.push(`start: ${v.start}`)
  if (v.end) bits.push(`end: ${v.end}`)
  if (v.watchFor) bits.push(`watchFor: ${JSON.stringify(v.watchFor)}`)
  bits.push(`checks: ${v.checks}`)
  if (v.bench) bits.push('bench: true')
  return `  { ${bits.join(', ')} },`
}

/** The file's whole text, so the audit can compare without writing anything. */
export async function renderIndex(): Promise<string> {
  const videos = await collectVideos()
  return `${HEAD}\nexport const SE_VIDEOS: SeVideoRef[] = [\n${videos.map(line).join('\n')}\n]\n`
}

/** `path` comes from the runner: this module is bundled to a temp dir first. */
export async function writeIndex(path: string): Promise<number> {
  const videos = await collectVideos()
  writeFileSync(path, await renderIndex())
  const subs = new Set(videos.map((v) => v.subtopicId))
  const dupes = videos.length - new Set(videos.map((v) => v.youtube)).size
  const hours = videos.reduce((n, v) => n + (v.end ?? v.seconds) - (v.start ?? 0), 0) / 3600
  console.log(`🎬 ${videos.length} videos across ${subs.size} subtopics · ${hours.toFixed(1)}h of film`)
  if (dupes) console.log(`   ${dupes} of them is the same upload used in more than one chapter`)
  console.log(`   written to src/steugene/videoIndex.ts`)
  return videos.length
}
